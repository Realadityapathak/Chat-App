export const updateProfile = async (req, res) => {
  try {
    const { profilePic, theme } = req.body;
    if (!profilePic && !theme) {
      return res
        .status(400)
        .json({ message: "Profile picture or theme is required" });
    }

    const userId = req.user._id;
    const updateData = {};

    if (profilePic) {
      if (typeof profilePic !== "string") {
        return res
          .status(400)
          .json({ message: "Invalid profile picture format" });
      }
      const uploadResponse = await cloudinary.uploader.upload(profilePic);
      updateData.profilePic = uploadResponse.secure_url;
    }

    if (theme !== undefined) {
      if (typeof theme !== "string" || !ALLOWED_THEMES.includes(theme)) {
        return res.status(400).json({ message: "Invalid theme selection" });
      }
      updateData.theme = theme;
    }

    const updatedUser = await User.findByIdAndUpdate(userId, updateData, {
      new: true,
    }).select("-password");

    res.status(200).json(updatedUser);
  } catch (error) {
    console.log("Error in update profile:", error);
    res.status(500).json({ message: "Internal server error" });
  }
};
